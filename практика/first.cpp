// Числовая лестница
// Без готового решения
// Условие: напиши программу на C++, которая выводит числовую лестницу из 5 строк с помощью двух вложенных циклов for.
// Каждая новая строка должна содержать на одну цифру больше, чем предыдущая. При этом цифра в строке равна номеру самой строки.
// Ожидаемый результат:
// 1
// 22
// 333
// 4444
// 55555

#include <iostream>
using namespace std;

int main(){
    for(int i = 1; i <= 5; i++){
        for(int j = 1; j <= i; j++){
            cout << i;
        }
        cout << endl;
    }
}